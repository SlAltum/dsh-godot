/** Boot `SceneTree` source; `__BRIDGE_PATH__` is replaced by {@link bootstrapSource}. */
export const BOOT_SOURCE: readonly string[] = [
  'extends SceneTree',
  '',
  '## Ego boot: a temporary main loop that loads the bridge from outside the',
  '## project, then starts the project scene. `project.godot` stays untouched.',
  '',
  'const BRIDGE_PATH := "__BRIDGE_PATH__"',
  '',
  '',
  'func _initialize() -> void:',
  '\tvar bridge_path := BRIDGE_PATH',
  '\tif bridge_path.is_empty():',
  '\t\tbridge_path = OS.get_environment("DSH_EGO_BRIDGE")',
  '\tif bridge_path.is_empty():',
  '\t\tpush_error("ego boot: missing DSH_EGO_BRIDGE")',
  '\t\tquit(2)',
  '\t\treturn',
  '\tvar bridge: Node = load(bridge_path).new()',
  '\tbridge.name = "EgoBridge"',
  '\troot.add_child(bridge)',
  '\tcall_deferred("_load_main_scene")',
  '',
  '',
  'func _load_main_scene() -> void:',
  '\tvar main_scene := OS.get_environment("DSH_EGO_SCENE")',
  '\tif main_scene.is_empty():',
  '\t\tmain_scene = str(ProjectSettings.get_setting("application/run/main_scene", ""))',
  '\tif main_scene.is_empty():',
  '\t\treturn',
  '\tchange_scene_to_file(main_scene)',
]

/** Options for {@link bridgeSource}. */
export interface BridgeSourceOptions {
  /** Compile-time eval gate (a runtime env `DSH_EGO_ALLOW_EVAL=1` still wins). */
  readonly allowEval?: boolean
}

/** Options for {@link bootstrapSource}. */
export interface BootstrapSourceOptions {
  /** Bridge script path embedded in the boot source (env var is the fallback). */
  readonly bridgePath?: string
}

/**
 * Render the bridge source.
 * @param options - the eval gate baked into the script.
 * @returns the GDScript text.
 */
export function bridgeSource(options: BridgeSourceOptions = {}): string {
  const allowEval = options.allowEval === true ? 'true' : 'false'
  const lines = [...BRIDGE_SOURCE]
  lines.splice(1, 0, '', `const ALLOW_EVAL := ${allowEval}`)
  return lines.join('\n')
}

/**
 * Render the boot source with a bridge path embedded safely.
 * @param options - the bridge path; omitted means "read DSH_EGO_BRIDGE".
 * @returns the GDScript text.
 */
export function bootstrapSource(options: BootstrapSourceOptions = {}): string {
  const encoded = JSON.stringify(options.bridgePath ?? '')
  return BOOT_SOURCE.map(line => line.replace('"__BRIDGE_PATH__"', encoded)).join('\n')
}
